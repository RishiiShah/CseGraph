def _target(
    path: str, line: int, *, name: str | None = None, id: str | None = None
) -> dict[str, Any]:
    value: dict[str, Any] = {"path": path, "line": line}
    if name is not None:
        value["name"] = name
    if id is not None:
        value["id"] = id
    return value


def _evidence(path: str, line: int, *, role: str | None = None) -> dict[str, Any]:
    value: dict[str, Any] = {"path": path, "line": line}
    if role is not None:
        value["role"] = role
    return value


def _range(path: str, start: int, end: int) -> dict[str, Any]:
    return {"path": path, "lines": [start, end]}


def _task(
    repo: str,
    task_id: str,
    category: str,
    prompt: str,
    *,
    target: str | None = None,
    status: str = "ready",
    expected_target: dict[str, Any] | None = None,
    candidates: tuple[dict[str, Any], ...] = (),
    evidence: tuple[dict[str, Any], ...] = (),
    permitted: tuple[dict[str, Any], ...] = (),
    **extra: Any,
) -> dict[str, Any]:
    value: dict[str, Any] = {
        "id": task_id,
        "repo": repo,
        "category": category,
        "task": prompt,
        "expected_status": status,
    }
    if target is not None:
        value["target"] = target
    if expected_target is not None:
        value["expected_target"] = expected_target
    if candidates:
        value["expected_candidates"] = list(candidates)
    if evidence:
        value["required_evidence"] = list(evidence)
    if permitted:
        value["permitted_ranges"] = list(permitted)
    value.update(extra)
    return value


