def _repository_commit(repo: str, repo_root: Path) -> str:
    if repo.startswith("benchmarks/fixtures/"):
        return _fixture_revision(repo_root / repo)
    return PINNED_SANDBOX_COMMITS[repo]


def build_adaptive_corpus(name: str, *, repo_root: Path) -> AdaptiveBenchmarkCorpus:
    """Build a named corpus without reading a tracked manifest file."""

    normalized = name.strip().lower()
    if normalized not in CORPUS_NAMES:
        raise ValueError(f"Unknown adaptive corpus {name!r}; expected one of {CORPUS_NAMES!r}")
    root = Path(repo_root).resolve()
    tasks = [dict(task) for task in _TASKS[normalized]]
    repositories = sorted({task["repo"] for task in tasks})
    commits = {repo: _repository_commit(repo, root) for repo in repositories}
    payload = {
        "schema_version": TASK_SCHEMA_VERSION_V2,
        "corpus_version": CORPUS_VERSIONS[normalized],
        "tier": normalized,
        "status": "ready",
        "repositories": {
            repo: {"url": REPOSITORY_URLS[repo], "commit": commits[repo]} for repo in repositories
        },
        "tasks": [dict(task, commit=commits[task["repo"]]) for task in tasks],
    }
    return load_adaptive_corpus(payload, path=Path(f"<generated:{normalized}>"))
